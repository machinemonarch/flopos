static int same(const u8 *a, const u8 *b, int n)
{
    int i;
    for (i = 0; i < n; i++) if (a[i] != b[i]) return 0;
    return 1;
}

static int report(const char *what, int ok)
{
    int n = 0;
    term_colour(ok ? C_TEXT : C_ACCENT);
    term_print(what);
    while (what[n]) n++;
    while (n++ < 23) term_putc(' ');
    term_print(ok ? "right" : "WRONG");
    term_newline();
    return ok;
}

int crypto_selftest(void)
{
    static u8 big[1000], out[200], buf[200];
    static const char fox[] = "The quick brown fox jumps over the lazy dog";
    static const char pt[] = "Ladies and Gentlemen of the class of '99: If I could offer you only one tip for the future, sunscreen would be it.";
    u8 key[32], nonce[12], salt[13], ikm[22], info[10], sec[32];
    int i, ok = 1, len = (int)sizeof pt - 1;
    u32 t0, ms;

    for (i = 0; i < 1000; i++) big[i] = (u8)((i * 31 + 7) & 0xFF);
    sha256((const u8 *)"abc", 3, out);
    ok &= report("sha256 short", same(out, V_SHA_ABC, 32));
    sha256(big, 1000, out);
    ok &= report("sha256 long", same(out, V_SHA_BIG, 32));

    hmac_sha256((const u8 *)"key", 3, (const u8 *)fox, sizeof fox - 1, out);
    ok &= report("hmac-sha256", same(out, V_HMAC, 32));

    for (i = 0; i < 13; i++) salt[i] = (u8)i;
    for (i = 0; i < 22; i++) ikm[i] = 0x0b;
    for (i = 0; i < 10; i++) info[i] = (u8)(0xf0 + i);
    {
        u8 prk[32];
        hkdf_extract(salt, 13, ikm, 22, prk);
        hkdf_expand(prk, info, 10, out, 42);
    }
    ok &= report("hkdf", same(out, V_HKDF, 42));

    for (i = 0; i < 32; i++) key[i] = (u8)i;
    nonce[0] = 7; nonce[1] = nonce[2] = nonce[3] = 0;
    for (i = 4; i < 12; i++) nonce[i] = (u8)(0x40 + i - 4);
    aead_seal(key, nonce, (const u8 *)"flopos", 6, (const u8 *)pt, (u32)len, out, out + len);
    ok &= report("chacha20-poly1305", same(out, V_AEAD, len + 16));
    ok &= report("  opening it again", aead_open(key, nonce, (const u8 *)"flopos", 6,
                                                  V_AEAD, (u32)len, V_AEAD + len, buf) &&
                                        same(buf, (const u8 *)pt, len));
    out[3] ^= 0x10;
    ok &= report("  refusing a forgery", !aead_open(key, nonce, (const u8 *)"flopos", 6,
                                                     out, (u32)len, out + len, buf));

    for (i = 0; i < 32; i++) sec[i] = (u8)(i * 7 + 1);
    t0 = ms_now();
    x25519_public(out, sec);
    ms = ms_now() - t0;
    ok &= report("x25519 public key", same(out, V_X_PUB, 32));
    x25519(out, sec, V_X_PEER);
    ok &= report("x25519 shared secret", same(out, V_X_SHARED, 32));

    term_colour(C_DIM);
    term_printf("one key exchange takes %u ms on this machine", ms);
    term_newline();

    /* The post-quantum half, and AES. */
    sha3_256((const u8 *)"abc", 3, out);
    ok &= report("sha3-256", same(out, V_SHA3, 32));
    shake128((const u8 *)"flopos", 6, out, 40);
    ok &= report("shake128", same(out, V_SHAKE, 40));
    {
        static u8 ek[MLKEM_EK], dk[MLKEM_DK], ct[MLKEM_CT], both[MLKEM_EK + MLKEM_DK];
        u8 k1[32], k2[32], m[32];
        u32 t_kg, t_dec;
        t0 = ms_now();
        mlkem_keygen(V_KEM_D, V_KEM_Z, ek, dk);
        t_kg = ms_now() - t0;
        for (i = 0; i < MLKEM_EK; i++) both[i] = ek[i];
        for (i = 0; i < MLKEM_DK; i++) both[MLKEM_EK + i] = dk[i];
        sha256(both, MLKEM_EK + MLKEM_DK, out);
        ok &= report("ml-kem-768 keys (nist)", same(out, V_KEM_HASH, 32));
        for (i = 0; i < 32; i++) m[i] = (u8)(i * 3);
        mlkem_encaps(ek, m, ct, k1);
        t0 = ms_now();
        mlkem_decaps(dk, ct, k2);
        t_dec = ms_now() - t0;
        ok &= report("ml-kem-768 agreement", same(k1, k2, 32));
        ct[5] ^= 1;
        mlkem_decaps(dk, ct, k2);
        ok &= report("  refusing a forgery", !same(k1, k2, 32));
        term_colour(C_DIM);
        term_printf("ml-kem key %u ms, opening a share %u ms", t_kg, t_dec);
        term_newline();
    }
    {
        u8 k[16], iv[12];
        static const char msg[] = "Ladies and Gentlemen of the class of '99";
        int ml = (int)sizeof msg - 1;
        for (i = 0; i < 16; i++) k[i] = (u8)i;
        for (i = 0; i < 12; i++) iv[i] = (u8)(100 + i);
        aesgcm_seal(k, iv, (const u8 *)"flopos", 6, (const u8 *)msg, (u32)ml, out, out + ml);
        ok &= report("aes-128-gcm", same(out, V_GCM, ml + 16));
    }
    {   /* Checked against OpenSSL (the Python `cryptography` package) and hashlib on the PC. */
        static const u8 want[80] = {
            0xdf, 0x30, 0x46, 0x89, 0xae, 0x16, 0x18, 0xb5, 0x17, 0x90, 0xaa, 0x92, 0xfd, 0xe6, 0xcb, 0x57, 0xb9, 0xc8, 0x9a, 0xb2,
            0x15, 0x5e, 0xc1, 0x3b, 0x3c, 0x38, 0xf9, 0xb6, 0xbb, 0x7f, 0xed, 0xd4, 0x66, 0x7b, 0xdb, 0xc6, 0xeb, 0xe3, 0x45, 0x36,
            0x6c, 0xd6, 0x67, 0x10, 0xd2, 0x00, 0x2d, 0x55, 0x5e, 0x54, 0xe5, 0x82, 0xfc, 0x71, 0x70, 0x07, 0x74, 0xb7, 0xbd, 0xf9,
            0x56, 0xce, 0xd6, 0xbd, 0x7e, 0xd4, 0x1a, 0x98, 0x97, 0x0f, 0xb3, 0xb7, 0x82, 0x21, 0x03, 0xb2, 0xcb, 0x8c, 0x3c, 0x08 };
        static const u8 wantk[32] = {
            0xa6, 0x9b, 0x17, 0x9e, 0x3a, 0xdd, 0x3c, 0x1e, 0x0a, 0xaf, 0x22, 0x7a, 0x0e, 0xb3, 0xaa, 0x2a,
            0xa8, 0x64, 0x5a, 0xb8, 0x6f, 0xec, 0xf6, 0xca, 0x00, 0xc1, 0x75, 0x12, 0x69, 0x7c, 0x71, 0x9e };
        static const char msg[] = "Now hear 'dis: a tape, a passphrase, and nobody else's business.";
        u8 k[32], iv[12], sl[16];
        for (i = 0; i < 32; i++) k[i] = (u8)i;
        iv[0] = 7; iv[1] = iv[2] = iv[3] = 0;
        for (i = 4; i < 12; i++) iv[i] = (u8)(0x40 + i - 4);
        aes256gcm_seal(k, iv, (const u8 *)"flopos", 6, (const u8 *)msg, 64, out, out + 64);
        ok &= report("aes-256-gcm", same(out, want, 80));
        out[5] ^= 1;
        ok &= report("  refusing a forgery", !aes256gcm_open(k, iv, (const u8 *)"flopos", 6, out, 64, out + 64, buf));
        for (i = 0; i < 16; i++) sl[i] = (u8)i;
        t0 = ms_now();
        pbkdf2_sha256((const u8 *)"correct horse battery staple", 28, sl, 16, 1000, k);
        ms = ms_now() - t0;
        ok &= report("pbkdf2-sha256", same(k, wantk, 32));
        term_colour(C_DIM);
        term_printf("a thousand rounds of it take %u ms on this machine", ms);
        term_newline();
        serial_printf("[crypto] pbkdf2 1000 rounds %u ms\n", ms);
    }
    {
        /* What checking a certificate costs here: one RSA-2048 signature,
         * one on each curve.  A site's chain is usually two or three of
         * these, and the handshake one more. */
        static const u8 e[3] = { 1, 0, 1 };
        u8 h[64];
        u32 t_rsa, t_256, t_384;
        Sha512 c;
        sha512_init(&c, 1); sha512_update(&c, (const u8 *)"abc", 3); sha512_final(&c, h);
        ok &= report("sha-384", same(h, V_SHA384_ABC, 48));
        sha512_init(&c, 0); sha512_update(&c, (const u8 *)"abc", 3); sha512_final(&c, h);
        ok &= report("sha-512", same(h, V_SHA512_ABC, 64));

        sha256((const u8 *)"FLOPOS", 6, h);
        t0 = ms_now();
        ok &= report("rsa-2048 signature", rsa_verify_pkcs1(V_RSA_N, 256, e, 3, V_RSA_PKCS1, 256, HASH_SHA256, h));
        t_rsa = ms_now() - t0;
        ok &= report("  rsa-pss signature", rsa_verify_pss(V_RSA_N, 256, e, 3, V_RSA_PSS, 256, HASH_SHA256, h, 32));
        h[0] ^= 1;
        ok &= report("  refusing a forgery", !rsa_verify_pkcs1(V_RSA_N, 256, e, 3, V_RSA_PKCS1, 256, HASH_SHA256, h));
        h[0] ^= 1;
        t0 = ms_now();
        ok &= report("ecdsa p-256 signature", ecdsa_verify(CURVE_P256, V_P256_PUB, 65, V_P256_SIG, (int)sizeof V_P256_SIG, h, 32));
        t_256 = ms_now() - t0;
        h[5] ^= 4;
        ok &= report("  refusing a forgery", !ecdsa_verify(CURVE_P256, V_P256_PUB, 65, V_P256_SIG, (int)sizeof V_P256_SIG, h, 32));
        hash_buf(HASH_SHA384, (const u8 *)"FLOPOS", 6, h);
        t0 = ms_now();
        ok &= report("ecdsa p-384 signature", ecdsa_verify(CURVE_P384, V_P384_PUB, 97, V_P384_SIG, (int)sizeof V_P384_SIG, h, 48));
        t_384 = ms_now() - t0;
        term_colour(C_DIM);
        term_printf("checking: rsa %u ms, p-256 %u ms, p-384 %u ms", t_rsa, t_256, t_384);
        term_newline();
        term_printf("%u authorities trusted, from ROOTS.DAT", (u32)x509_roots());
        term_newline();
    }
    term_colour(ok ? C_BRIGHT : C_ACCENT);
    term_print(ok ? "All of it is right." : "Something is wrong. Do not trust TLS on this build.");
    term_newline();
    return ok;
}
