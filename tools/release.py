#!/usr/bin/env python3
"""Bump the version, regenerate kernel/version.h, and name the next image.

Called by `make release`. Every image handed over gets its own number and
its own copy under releases/, so any build can be put back on a floppy
later without reconstructing it.
"""
import sys

part = sys.argv[1] if len(sys.argv) > 1 else "patch"

major, minor, patch = (int(x) for x in open("VERSION").read().strip().split("."))
if part == "major":   major, minor, patch = major + 1, 0, 0
elif part == "minor": minor, patch = minor + 1, 0
else:                 patch += 1

version = "%d.%d.%d" % (major, minor, patch)
open("VERSION", "w").write(version + "\n")
open("kernel/version.h", "w").write(
    '/* GENERATED by tools/release.py. Do not hand edit. */\n'
    '#ifndef VERSION_H\n#define VERSION_H\n'
    '#define FLOPOS_VERSION "%s"\n'
    '#endif\n' % version)
print(version)
