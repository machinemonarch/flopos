# The pointed letters Yiddish spells with, as Unicode has them made up:
# (letter, the base, what is added).  Points: a bar under (patah), a bar
# and a dot under (qamats), a dot under (hiriq), a dot inside (dagesh), a
# bar over (rafe), a dot over at the left (sin).
POINTED = [
    ("יִ", "י", "hiriq"),            # yod with hiriq
    ("ײַ", "ײ", "patah"),            # double yod with patah
    ("שׂ", "ש", "sin"),              # shin with sin dot
    ("אַ", "א", "patah"),            # alef with patah
    ("אָ", "א", "qamats"),           # alef with qamats
    ("וּ", "ו", "dagesh"),           # vav with dagesh
    ("כּ", "כ", "dagesh"),           # kaf with dagesh
    ("פּ", "פ", "dagesh"),           # pe with dagesh
    ("תּ", "ת", "dagesh"),           # tav with dagesh
    ("בֿ", "ב", "rafe"),             # bet with rafe
    ("פֿ", "פ", "rafe"),             # pe with rafe
]
# Where the dot inside goes, by letter: (row of the five, column).
DAGESH5 = {"ו": (2, 0), "כ": (2, 2), "פ": (3, 2), "ת": (2, 3)}
DAGESH4 = {"ו": (2, 3), "כ": (2, 1), "פ": (2, 1), "ת": (2, 1)}


def _set(row, col, ch="#"):
    return row[:col] + ch + row[col + 1:]


def large(G, pad):
    out = {}
    for ch, rows in list(CYR5_UP.items()) + list(CYR5_LO.items()):
        out[ch] = pad(ch, rows)

    # Romanian: a breve over a and A, a comma under s, S, t and T.
    out["ă"] = pad("ă", ["#...#", ".###."] + G["a"][2:7])
    out["Ă"] = pad("Ă", ["#...#", ".###.", ".###.", "#...#", "#####", "#...#", "#...#"])
    for ch, base in (("ș", "s"), ("Ș", "S"), ("ț", "t"), ("Ț", "T")):
        out[ch] = pad(ch, G[base][:7] + ["..#.."])

    def heb(ch, body, top=".....", down=None, under=(".....", ".....")):
        d = down or HEB5_DOWN.get(ch)
        below = (d, d) if d else under
        return pad(ch, [HEB5_TOP.get(ch, top)] + list(body) + list(below))

    for ch, body in HEB5.items():
        out[ch] = heb(ch, body)
    for ch, base, mark in POINTED:
        body = list(HEB5[base])
        top, under = HEB5_TOP.get(base, "....."), (".....", ".....")
        if mark == "patah":  under = (".###.", ".....")
        if mark == "qamats": under = (".###.", "..#..")
        if mark == "hiriq":  under = ("..#..", ".....")
        if mark == "rafe":   top = ".###."
        if mark == "sin":    top = "#...."
        if mark == "dagesh":
            r, c = DAGESH5[base]
            body[r] = _set(body[r], c)
        out[ch] = heb(ch, body, top=top, under=under)
    return out, dict(ALIAS)


