/* ===========================================================================
 * selftest.c -- the `crypto` instrument.
 *
 * The encryption code was checked against OpenSSL on thousands of random
 * inputs, but on a 64-bit machine.  This machine is 32-bit, and a compiler
 * doing 64-bit multiplication on a 32-bit processor is exactly where a
 * subtle difference would hide.  So the same code is checked again here,
 * on the processor that will run it, against answers OpenSSL gave for
 * fixed inputs -- and the key exchange is timed, because a TLS handshake
 * on a 119MHz Pentium waits on it.
 * ===========================================================================
 */
